#!/usr/bin/env python3
"""Write docs/sample-size.md, the sample-size tables behind `evalsig power`.

Three tables:
  1. Items needed to claim a disagreement rate below u when none is observed (exact
     Clopper-Pearson and Wilson).
  2. Items needed to measure a rate to within ±w (the Wilson half-width).
  3. Items needed to detect an accuracy difference δ between two systems on the same
     items (the power of the exact McNemar test, summed exactly).

The Rust module `evalsig_core::power` renders the same file; a test compares them.

Usage: uv run --project scripts scripts/sample_size.py [--out PATH]
"""
import argparse
import math
from functools import lru_cache
from pathlib import Path

from scipy import stats

OUT = Path(__file__).resolve().parent.parent / "docs" / "sample-size.md"
Z1 = stats.norm.ppf(0.95)
Z2 = stats.norm.ppf(0.975)


def zero_event_n(u):
    exact = math.ceil(math.log(0.05) / math.log(1 - u))
    wil = math.ceil(Z1 ** 2 * (1 - u) / u)
    return exact, wil


def wilson_halfwidth(k, n, z=Z2):
    p = k / n
    d = 1 + z * z / n
    return z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d


def n_for_halfwidth(p, w):
    n = 2
    while wilson_halfwidth(round(p * n), n) > w:
        n += 1 if n < 200 else max(1, n // 200)
    return n


@lru_cache(maxsize=None)
def lower_crit(d, alpha):
    """The largest b that the two-sided exact binomial test rejects among d discordant
    pairs (reject when b <= k), or -1 when none."""
    k = -1
    while k + 1 <= d // 2 and min(1.0, 2 * stats.binom.cdf(k + 1, d, 0.5)) <= alpha:
        k += 1
    return k


def mcnemar_power(n, p10, p01, alpha=0.05):
    psi = p10 + p01
    q = p10 / psi
    pw = 0.0
    for d in range(n + 1):
        pd = stats.binom.pmf(d, n, psi)
        if pd < 1e-15:
            continue
        k = lower_crit(d, alpha)
        if k < 0:
            continue
        pw += pd * (stats.binom.cdf(k, d, q) + stats.binom.sf(d - k - 1, d, q))
    return pw


def mcnemar_n_exact(p10, p01, power=0.8, alpha=0.05):
    """The smallest n whose power reaches `power`. The exact test's power is not
    monotone in n, so the first n of a run of 20 evaluated points that all reach it."""
    n, streak, first = 10, 0, None
    while n < 20000:
        if mcnemar_power(n, p10, p01, alpha) >= power:
            first = first or n
            streak += 1
            if streak >= 20:
                return first
        else:
            first, streak = None, 0
        n += 1 if n < 400 else 5
    return None


def mcnemar_n_connor(p10, p01, power=0.8, alpha=0.05):
    psi, delta = p10 + p01, abs(p10 - p01)
    zb = stats.norm.ppf(power)
    za = stats.norm.ppf(1 - alpha / 2)
    return math.ceil((za * math.sqrt(psi) + zb * math.sqrt(psi - delta ** 2)) ** 2 / delta ** 2)


def render():
    lines = [
        "# Sample sizes",
        "",
        "Generated by `scripts/sample_size.py`; `evalsig_core::power` renders the same file.",
        "The unit is the item. Replicates of the same item do not add to the count (see",
        "\"Replicates and item counts\" below).",
        "",
        "## 1. Items to claim a disagreement rate below u with none observed (one-sided 95%)",
        "",
        "| u | Exact (Clopper-Pearson) | Wilson | Rule of thumb (3/u) |",
        "|---|---|---|---|",
    ]
    for u in [0.1, 0.05, 0.02, 0.01, 0.005, 0.001]:
        e, w = zero_event_n(u)
        lines.append(f"| {u:g} | {e} | {w} | {math.ceil(3 / u)} |")
    lines += [
        "",
        "- With no events Wilson's upper bound is too small, so it passes with about 10% fewer",
        "  items than the exact method. Gates use the exact method; Wilson is for the two-sided",
        "  interval shown in reports.",
        "",
        "## 2. Items to measure a rate to within ±w (half-width of the 95% interval)",
        "",
        "| Rate p | w=0.10 | w=0.05 | w=0.03 | w=0.02 |",
        "|---|---|---|---|---|",
    ]
    for p in [0.5, 0.2, 0.1, 0.05]:
        lines.append(f"| {p:g} | " + " | ".join(str(n_for_halfwidth(p, w)) for w in [0.10, 0.05, 0.03, 0.02]) + " |")
    lines += [
        "",
        "- Rates whose denominator is one class (hit rate, false-alarm rate) are read with that",
        "  class's count. At 10% prevalence, measuring the positive side to ±0.05 takes about ten",
        "  times the table's value in items overall.",
        "",
        "## 3. Items to detect an accuracy difference δ between two systems on the same items",
        "",
        "Exact McNemar test (two-sided α = 0.05) with power 0.8. ψ is the share of items only one",
        "system gets right (the discordance). Exact sums the power over the binomial",
        "distributions; the approximation is Connor (1987).",
        "",
        "| δ | ψ | Exact | Approximation |",
        "|---|---|---|---|",
    ]
    for delta in [0.10, 0.05, 0.03]:
        for psi in [0.10, 0.20, 0.30]:
            if delta >= psi:
                continue
            p10, p01 = (psi + delta) / 2, (psi - delta) / 2
            lines.append(f"| {delta:g} | {psi:g} | {mcnemar_n_exact(p10, p01)} | {mcnemar_n_connor(p10, p01)} |")
    lines += [
        "",
        "- For the same δ, a larger ψ (the systems fail on different items) needs more items.",
        "  When ψ is unknown, measure it on a small pilot run and pass it to `power`.",
        "",
        "## Replicates and item counts",
        "",
        "When each item's value is the mean of K replicates, with between-item variance σ_b² and",
        "within-item (between-replicate) variance σ_w², the mean of n items has variance",
        "(σ_b² + σ_w²/K) / n. More replicates shrink only the σ_w² term; the σ_b² term shrinks",
        "only with more items. Counting replicates as independent items makes intervals too narrow.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT)
    out = ap.parse_args().out
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
